--------------------------------------------------------
--  DDL for Trigger TRG_TEST
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "KNRAMES"."TRG_TEST" 
   AFTER INSERT OR UPDATE OR DELETE
   ON KNRAMES.TB_TEMP_NOT_USE
   FOR EACH ROW
DECLARE 
   V_TIMEKEY VARCHAR(40);
BEGIN
   IF INSERTING THEN
     sys.dbms_session.sleep(0.5);
     SELECT TO_CHAR(SYSTIMESTAMP, 'YYYYMMDDHH24MISSFF') INTO V_TIMEKEY FROM DUAL;
   ELSIF UPDATING THEN
     dbms_lock.sleep(0.01);
     SELECT TO_CHAR(SYSTIMESTAMP, 'YYYYMMDDHH24MISSFF') INTO V_TIMEKEY FROM DUAL;
   ELSIF DELETING THEN
      SELECT TO_CHAR(SYSTIMESTAMP, 'YYYYMMDDHH24MISSFF') INTO V_TIMEKEY FROM DUAL;
   END IF;
END TRG_TEST;
/
ALTER TRIGGER "KNRAMES"."TRG_TEST" ENABLE;
