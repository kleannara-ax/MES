 * 메뉴 등록 : WRK55 화장지 실적 현황 (모니터링 > WRK46 과 동일 레벨)
 *
 *  - MSTMENU   : 메뉴 마스터 (부모 정보 없음)
 *  - MSTMENUGL : 메뉴그룹별 트리 배치 (PMENUID = 부모, SORTORDER = 순서)  ← 위치 결정
 *  - SYSLABEL  : 메뉴 표시명 (LABELGID='MENU', LABELID = MSTMENU.MENULABEL)
 *
 *  ※ WRK46 이 할당된 "모든 메뉴그룹"에 같은 부모로 복사하므로
 *    WRK46 을 볼 수 있는 사용자는 WRK55 도 보게 됩니다.
 *==============================================================================*/

/* 0. 사전 확인 ------------------------------------------------------------- */
-- 0-1) WRK46 의 부모(모니터링) MENUID 와 메뉴그룹별 정렬순서
SELECT MGL.MENUGID, MGL.MENUID, MGL.PMENUID, MGL.SORTORDER, P.MENUNAME AS PARENT_NAME
  FROM KNRAMES.MSTMENUGL MGL
  LEFT JOIN KNRAMES.MSTMENU P ON P.COMPID = MGL.COMPID AND P.MENUID = MGL.PMENUID
 WHERE MGL.COMPID = 'KN'
   AND MGL.MENUID = 'WRK46';

-- 0-2) 같은 부모 아래 형제 메뉴 순서 (WRK55 를 어디에 끼울지 결정)
SELECT MGL.MENUGID, MGL.MENUID, MM.MENUNAME, MGL.SORTORDER
  FROM KNRAMES.MSTMENUGL MGL
  JOIN KNRAMES.MSTMENU   MM ON MM.COMPID = MGL.COMPID AND MM.MENUID = MGL.MENUID
 WHERE (MGL.COMPID, MGL.MENUGID, MGL.PMENUID) IN (SELECT COMPID, MENUGID, PMENUID
                                                    FROM KNRAMES.MSTMENUGL
                                                   WHERE COMPID = 'KN' AND MENUID = 'WRK46')
 ORDER BY MGL.MENUGID, MGL.SORTORDER;

-- 0-3) WRK55 미사용 확인 (0 건이어야 함)
SELECT 'MSTMENU' T, COUNT(*) FROM KNRAMES.MSTMENU   WHERE COMPID = 'KN' AND MENUID = 'WRK55'
UNION ALL
SELECT 'MSTMENUGL', COUNT(*) FROM KNRAMES.MSTMENUGL WHERE COMPID = 'KN' AND MENUID = 'WRK55'
UNION ALL
SELECT 'SYSLABEL',  COUNT(*) FROM KNRAMES.SYSLABEL  WHERE LABELGID = 'MENU' AND LABELID = 'WRK55';


/* 1. 메뉴 마스터 ----------------------------------------------------------- */
INSERT INTO KNRAMES.MSTMENU (COMPID, MENUID, MENULABEL, MENUNAME, MENUTYPE, MAUTHTYPE, URI, PARAM,
                             SORTORDER, CREATEUSER, CREATEDATE, UPDATEUSER, UPDATEDATE, DELETEYN)
VALUES ('KN', 'WRK55', 'WRK55', '화장지 실적 현황', ' ', NULL, '/mes/wrk/WRK55.page', ' ',
        1591, 'DEV', SYSDATE, 'DEV', SYSDATE, 'N');


/* 2. 트리 배치 : WRK46 과 같은 부모 / WRK46 바로 다음 순서 ------------------- */
INSERT INTO KNRAMES.MSTMENUGL (COMPID, MENUGID, MENUID, SORTORDER, PMENUID,
                               CREATEUSER, CREATEDATE, UPDATEUSER, UPDATEDATE)
SELECT MGL.COMPID, MGL.MENUGID, 'WRK55', MGL.SORTORDER + 1, MGL.PMENUID,
       'DEV', SYSDATE, 'DEV', SYSDATE
  FROM KNRAMES.MSTMENUGL MGL
 WHERE MGL.COMPID = 'KN'
   AND MGL.MENUID = 'WRK46'
   AND NOT EXISTS (SELECT 1 FROM KNRAMES.MSTMENUGL X
                    WHERE X.COMPID = MGL.COMPID AND X.MENUGID = MGL.MENUGID AND X.MENUID = 'WRK55');
-- ※ 0-2 결과에서 WRK46 SORTORDER+1 이 이미 다른 메뉴와 겹치면
--   순서가 섞일 수 있으니 SORTORDER 를 원하는 값으로 직접 UPDATE 하세요.


/* 3. 메뉴 라벨 : WRK46 라벨 행을 복사해 언어별로 생성 ----------------------- */
INSERT INTO KNRAMES.SYSLABEL (LABELGID, LABELID, LANGCODE, LABEL, LABELTYPE, COMPID, DELETEYN,
                              CREATEUSER, CREATEDATE, UPDATEUSER, UPDATEDATE)
SELECT L.LABELGID, 'WRK55', L.LANGCODE,
       CASE WHEN L.LANGCODE = 'KR' THEN '화장지 실적 현황' ELSE 'Tissue Production Status' END,
       L.LABELTYPE, L.COMPID, 'N',
       'DEV', SYSDATE, 'DEV', SYSDATE
  FROM KNRAMES.SYSLABEL L
 WHERE L.LABELGID = 'MENU'
   AND L.LABELID  = 'WRK46'
   AND NOT EXISTS (SELECT 1 FROM KNRAMES.SYSLABEL X
                    WHERE X.LABELGID = 'MENU' AND X.LABELID = 'WRK55' AND X.LANGCODE = L.LANGCODE);
-- ※ WRK46 라벨이 없으면 0 건 → 트리는 MSTMENU.MENUNAME 으로 표시되므로 문제 없음


/* 4. 결과 확인 ------------------------------------------------------------- */
SELECT MGL.MENUGID, MGL.MENUID, MGL.PMENUID, MGL.SORTORDER, MM.MENUNAME, MM.URI
  FROM KNRAMES.MSTMENUGL MGL
  JOIN KNRAMES.MSTMENU   MM ON MM.COMPID = MGL.COMPID AND MM.MENUID = MGL.MENUID
 WHERE MGL.COMPID = 'KN'
   AND MGL.MENUID IN ('WRK46', 'WRK55')
 ORDER BY MGL.MENUGID, MGL.SORTORDER;

