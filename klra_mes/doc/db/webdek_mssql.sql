  SELECT 
    SL.MESSAGEGID, 
    SL.MESSAGEID, 
    KO.MESSAGE AS KO, 
    EN.MESSAGE AS EN, 
    ZH.MESSAGE AS ZH 
FROM 
(SELECT 
    MESSAGEGID, 
    MESSAGEID 
FROM SYSMESSAGE 
GROUP BY MESSAGEGID,MESSAGEID 
ORDER BY MESSAGEGID,MESSAGEID) SL  
LEFT OUTER JOIN SYSMESSAGE KO ON KO.LANGCODE = 'KO' AND SL.MESSAGEGID = KO.MESSAGEGID AND SL.MESSAGEID = KO.MESSAGEID 
