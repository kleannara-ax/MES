-- 5-2 동일 바코드가 INV001에 중복 (수신 프로시저가 오류 처리하는 조건)
SELECT WERKS, MATNR, IND_BCD, COUNT(*) row_cnt, SUM(STCK_QTY) qty
  FROM TB_INV001
 WHERE WERKS='P300'
   AND MATNR IN ('1400092','1400191','1400208','1400216','1400243','1401048','1401071','1410032')
 GROUP BY WERKS, MATNR, IND_BCD
HAVING COUNT(*) > 1;

-- 5-3 음수/요청수량 불일치
SELECT WERKS, MATNR, LOT_NO, IND_BCD, STCK_QTY, RET_REQ_QTY, UPDDATE, UPDID
  FROM TB_INV001
 WHERE WERKS='P300'
   AND MATNR IN ('1400092','1400191','1400208','1400216','1400243','1401048','1401071','1410032')
   AND (NVL(STCK_QTY,0) < 0 OR NVL(RET_REQ_QTY,0) < 0 OR NVL(RET_REQ_QTY,0) > NVL(STCK_QTY,0));

-- 5-4 INV003 산식 불일치(정상 정의가 STCK_QTY = IN_QTY - USE_QTY인 행만 적용)
SELECT WERKS, MATNR, LOT_NO, IND_BCD, SEQNO, IN_QTY, USE_QTY, STCK_QTY,
       NVL(IN_QTY,0)-NVL(USE_QTY,0) calc_qty
  FROM TB_INV003
 WHERE WERKS='P300'
   AND MATNR IN ('1400092','1400191','1400208','1400216','1400243','1401048','1401071','1410032')
   AND ABS(NVL(STCK_QTY,0) - (NVL(IN_QTY,0)-NVL(USE_QTY,0))) > 0.000001;

