
  CREATE OR REPLACE EDITIONABLE PROCEDURE "KNRAMES"."SP_AUTO_ERR_LOG" (
    P_MACH_CD   IN VARCHAR2,
    P_IND_BCD   IN VARCHAR2,
    P_ERR_TYPE  IN VARCHAR2,
    P_ERR_MSG   IN VARCHAR2,
    P_DEVICE_DT IN VARCHAR2,
    P_RMK       IN VARCHAR2
)
IS
BEGIN
    INSERT INTO TB_AUTO_ERR_LOG (
        MACH_CD, IND_BCD, ERR_TYPE, ERR_MSG, RMK, REGDATE, DEVICE_DATE
    ) VALUES (
        P_MACH_CD
        , P_IND_BCD
        , P_ERR_TYPE
        , P_ERR_MSG
        , P_RMK
        , SYSDATE
        , TO_DATE(P_DEVICE_DT, 'YYYY-MM-DD HH24:MI:SS')
    );
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'ERROR: ' || SQLERRM);
END;
/
