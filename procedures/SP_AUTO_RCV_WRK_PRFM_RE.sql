							V_LOT_NO_M, V_INP_DT_M, V_T_USE_QTY, V_T_USE_QTY - V_USE_QTY_M, V_T_USE_QTY -(V_T_USE_QTY - V_USE_QTY_M),
							V_UNIT_M, V_ROLLCNT_M, V_USE_QTY_M,
