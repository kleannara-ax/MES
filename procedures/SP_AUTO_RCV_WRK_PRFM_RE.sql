		RS_CODE := 'S';
		OPEN P_CUR_1 FOR
		SELECT V_IF_ID AS I_IF_ID
				, 'M' || LTRIM(RTRIM(TO_CHAR(SEQ_GET_IFR_KEY.NEXTVAL, '00000000000000000000000000000'))) AS I_IF_KEY
				, P_ERP_DOC_NO AS I_SDOC_NO
				, V_PRFM_FUNC AS I_PRFM_FUNC
				, V_PARAM_LIST AS I_PRFM_LIST
				, P_WMS_DOC_NO AS I_WDOC_NO
		FROM DUAL;
	ELSE
		RS_CODE := V_CODE;
		RS_MSG := V_MSG;
	END IF;

	IF RS_CODE = 'E' THEN
		ROLLBACK;
		RS_CODE := 'E';
--		RS_MSG  := RS_MSG;
		RETURN;
	END IF;


	--예외처리(catch)
	EXCEPTION
	WHEN E_EXCEPTION_USER THEN
		-- 에러 내역 SET
		E_SQL_ERR_CD        := SQLCODE;
		E_SQL_ERR_MSG       := SUBSTRB(SQLERRM,1,300);

		ROLLBACK;
		SP_PROC_ERROR(V_PLT_CD, V_PRG_NM, E_SQL_ERR_CD, E_SQL_ERR_MSG, V_SESS_USER_ID);

		RETURN;
	WHEN OTHERS THEN
		E_SQL_ERR_CD        := SQLCODE;
		E_SQL_ERR_MSG       := 'EXCEPTION OTHER ERROR. [' || SUBSTR(SQLERRM,1,500) || ']';

		ROLLBACK;
		RAISE_APPLICATION_ERROR(-20001, E_SQL_ERR_MSG);

		RETURN;
END SP_AUTO_RCV_WRK_PRFM_RE;
