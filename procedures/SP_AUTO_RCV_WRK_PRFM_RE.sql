				UPDID = V_SESS_USER_ID
		WHERE WERKS = P_WERKS 
			AND MACH_CD = P_MACH_CD
			AND IND_BCD = P_IND_BCD
			AND IND_BCD_M = V_IND_BCD_M
			AND USE_DIV = '1'
			AND MATNR_M = V_MATNR_M;   

