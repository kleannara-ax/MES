		INTO V_PRFM_FUNC
	FROM TB_ITFMA
	WHERE 1=1
	AND IFID = V_IF_ID;

    V_REQ_DATE := TO_CHAR(V_DATE, 'YYYYMMDD');
	V_PARAM_LIST := '{"CON_TYPE":"","CORE":"","SAUART":"","STOR_LOC_TO":"' || V_STOR_LOC_TO || '","EMPLY_NM":"' || V_EMPLY_NM || '","OVBELN":"","WERKS": "' ||P_WERKS || '","EMPLY_NO": "' || V_EMPLY_NO || '","IND_BCD":"' || P_IND_BCD || '","DOC_NO":"' || P_WMS_DOC_NO || '","ORDER_NO":"' || V_ORDER_NO || '","PACK_TYPE":"","OPOSNR":"","WLEN":"","QTY":"' ||V_PRFM_QTY || '","MACHINE":"' || V_MACHINE || '","WEIGHT":"","IF_GET_DATE":"' || V_DATE || '","STOR_LOC_FROM":"' || V_STOR_LOC_FROM || '","MATNR":"' || V_MATNR || '","IF_SET_DATE":"","KUNNR":"","RCVGDS_DT":"' || V_REQ_DATE || '","DOC_SEQNO":"' || V_DOC_SEQ || '","UNIT":"' || V_UNIT || '","SEND_YN":"N","NTN_CD":"KR","ORDER_SEQNO":"1","IF_MES_KEY":"","DLFL":"C","REQ_DT":"' || V_REQ_DATE || '","PRDC_DT":"' || V_PRFM_DT || '","IF_STATUS":"N","VLEN":"","STCK_NO":"","IF_ERR_MESS":"","PCODE":"","LOT_NO":"' || V_LOT_NO || '","DSTBT_DDLIN":"' || V_DSTBT_DDLIN || '"}';

