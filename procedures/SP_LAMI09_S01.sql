
  CREATE OR REPLACE EDITIONABLE PROCEDURE "KNRAMES"."SP_LAMI09_S01" (
	P_TYPE          IN    VARCHAR2, -- LIST, SAVE
	P_SDATE			IN    VARCHAR2, -- LIST, SAVE
	P_EDATE			IN    VARCHAR2, -- LIST, SAVE
	P_MATNR			IN    VARCHAR2,
	P_GBN			IN	  VARCHAR2,
	P_SUCCESS       OUT   VARCHAR2,
	P_RS_LIST       OUT   SYS_REFCURSOR 
)
/*==============================================================================
 * PROGRAM ID    : SP_LAMI09_S01
 * PROGRAM NAME  : 라미네이팅 슬리팅 품목변경 조회
 * VERSION       : 1.0.0
 * DESCRIPTION   : 라미네이팅 슬리팅 품목변경 내역을 조회한다.
 *=============================================================================*/


AS
	V_PRG_NM          	VARCHAR2(100) 	:= 'SP_LAMI09_S01';     -- PROCEDURE NAME

	-- 오라클 에러 처리용 변수선언 영역
    E_EXCEPTION_USER  	EXCEPTION;
    E_SQL_ERR_CD      	NUMBER(5) 		:= 0;
    E_SQL_ERR_MSG		VARCHAR2(4000);

   -- JSON을 위한 변수선언 영역
    V_JSON				JSON_OBJECT_T;
    V_ARR_LIST       	JSON_ARRAY_T;
	V_OBJ            	JSON_OBJECT_T;
    V_OBJSTR	 		VARCHAR2(4000);
   
    V_JSON_OBJ 			JSON_OBJECT_T;
    V_MAP_OBJ			JSON_OBJECT_T;

	-- 세션값 처리용 변수선언 영역
    V_SESS_USER_ID   	VARCHAR2(20);
    V_PLT_CD         	VARCHAR2(2);
   	V_DEBUG          	VARCHAR2(1);

	-- 조건절 처리용 변수선언 영역

	V_SQL				CLOB;
	V_IND_BCD			VARCHAR2(20);

BEGIN
	IF	P_TYPE	=	'LIST'	THEN
		
			IF	P_GBN = 'N'	THEN
				OPEN P_RS_LIST FOR
				SELECT	SUBSTR(W002.PRFM_DT, 1, 4) || '-' || SUBSTR(W002.PRFM_DT, 5, 2) || '-' || SUBSTR(W002.PRFM_DT, 7, 2) AS PRFM_DT,
						W002.MATNR, M001.MATNR_NM, W002.LOT_NO, W002.IND_BCD, W002.PRFM_QTY, W024.MATNR_TO,
						(SELECT MATNR_NM FROM TB_MAS001 WHERE WERKS = W024.WERKS_TO AND MATNR = W024.MATNR_TO) AS MATNR_TO_NM,
						CASE	WHEN	W024.BUDAT IS NULL	THEN	''
								ELSE	SUBSTR(W024.BUDAT, 1, 4) || '-' || SUBSTR(W024.BUDAT, 5, 2) || '-' || SUBSTR(W024.BUDAT, 7, 2)
						END	AS BUDAT,
						NVL(W024.MENGE, 0) AS MENGE,
						CASE	WHEN	NVL(W024.CNL_YN, 'Y') = 'N'	THEN	'변경'
						ELSE	'미변경'
						END		AS GBN
				FROM	TB_WRK002 W002 LEFT OUTER JOIN TB_WRK024 W024
							ON	W002.WERKS = W024.WERKS_FROM
							AND	W002.MATNR = W024.MATNR_FROM
							AND	W002.LOT_NO = W024.CHARG
							AND	W002.IND_BCD = W024.IND_BCD
						INNER JOIN	TB_MAS001 M001
							ON	W002.WERKS = M001.WERKS
							AND	W002.MATNR = M001.MATNR
							AND	M001.LGFSB = '2810'
				WHERE	W002.WERKS = 'P100'
				AND		W002.PRFM_DT BETWEEN P_SDATE AND P_EDATE
				AND		W002.MACH_CD IN ('PLP01', 'PLS01')
				AND		W002.MATNR LIKE P_MATNR || '%'
				AND		W024.MATNR_FROM IS NOT NULL
				AND		NVL(W002.CNL_YN, 'N') = 'N'
				ORDER	BY	1, 2, 3, 4;
			ELSIF	P_GBN = 'Y'	THEN
				OPEN P_RS_LIST FOR
				SELECT	SUBSTR(W002.PRFM_DT, 1, 4) || '-' || SUBSTR(W002.PRFM_DT, 5, 2) || '-' || SUBSTR(W002.PRFM_DT, 7, 2) AS PRFM_DT,
						W002.MATNR, M001.MATNR_NM, W002.LOT_NO, W002.IND_BCD, W002.PRFM_QTY, W024.MATNR_TO,
						(SELECT MATNR_NM FROM TB_MAS001 WHERE WERKS = W024.WERKS_TO AND MATNR = W024.MATNR_TO) AS MATNR_TO_NM,
						CASE	WHEN	W024.BUDAT IS NULL	THEN	''
								ELSE	SUBSTR(W024.BUDAT, 1, 4) || '-' || SUBSTR(W024.BUDAT, 5, 2) || '-' || SUBSTR(W024.BUDAT, 7, 2)
						END	AS BUDAT,
						NVL(W024.MENGE, 0) AS MENGE,
						CASE	WHEN	NVL(W024.CNL_YN, 'Y') = 'N'	THEN	'변경'
						ELSE	'미변경'
						END		AS GBN
				FROM	TB_WRK002 W002 LEFT OUTER JOIN TB_WRK024 W024
							ON	W002.WERKS = W024.WERKS_FROM
							AND	W002.MATNR = W024.MATNR_FROM
							AND	W002.LOT_NO = W024.CHARG
							AND	W002.IND_BCD = W024.IND_BCD
						INNER JOIN	TB_MAS001 M001
							ON	W002.WERKS = M001.WERKS
							AND	W002.MATNR = M001.MATNR
							AND	M001.LGFSB = '2810'
				WHERE	W002.WERKS = 'P100'
				AND		W002.PRFM_DT BETWEEN P_SDATE AND P_EDATE
				AND		W002.MACH_CD IN ('PLP01', 'PLS01')
				AND		NVL(W002.CNL_YN, 'N') = 'N'
				AND		W002.MATNR LIKE P_MATNR || '%'
				AND		W024.MATNR_FROM IS NULL
				ORDER	BY	1, 2, 3, 4;
			ELSE
				OPEN P_RS_LIST FOR
				SELECT	SUBSTR(W002.PRFM_DT, 1, 4) || '-' || SUBSTR(W002.PRFM_DT, 5, 2) || '-' || SUBSTR(W002.PRFM_DT, 7, 2) AS PRFM_DT,
						W002.MATNR, M001.MATNR_NM, W002.LOT_NO, W002.IND_BCD, W002.PRFM_QTY, W024.MATNR_TO,
						(SELECT MATNR_NM FROM TB_MAS001 WHERE WERKS = W024.WERKS_TO AND MATNR = W024.MATNR_TO) AS MATNR_TO_NM,
						CASE	WHEN	W024.BUDAT IS NULL	THEN	''
								ELSE	SUBSTR(W024.BUDAT, 1, 4) || '-' || SUBSTR(W024.BUDAT, 5, 2) || '-' || SUBSTR(W024.BUDAT, 7, 2)
						END	AS BUDAT,
						NVL(W024.MENGE, 0) AS MENGE,
						CASE	WHEN	NVL(W024.CNL_YN, 'Y') = 'N'	THEN	'변경'
						ELSE	'미변경'
						END		AS GBN
				FROM	TB_WRK002 W002 LEFT OUTER JOIN TB_WRK024 W024
							ON	W002.WERKS = W024.WERKS_FROM
							AND	W002.MATNR = W024.MATNR_FROM
							AND	W002.LOT_NO = W024.CHARG
							AND	W002.IND_BCD = W024.IND_BCD
--							AND	W024.MATNR_FROM LIKE P_MATNR || '%'
						INNER JOIN	TB_MAS001 M001
							ON	W002.WERKS = M001.WERKS
							AND	W002.MATNR = M001.MATNR
							AND	M001.LGFSB = '2810'
				WHERE	W002.WERKS = 'P100'
				AND		W002.MATNR LIKE P_MATNR || '%'
				AND		W002.PRFM_DT BETWEEN P_SDATE AND P_EDATE
				AND		W002.MACH_CD IN ('PLP01', 'PLS01')
				AND		NVL(W002.CNL_YN, 'N') = 'N'
				ORDER	BY	1, 2, 3, 4;
			END IF;

		P_SUCCESS := 'Y';
	ELSIF	P_TYPE = 'LIST1'	THEN
		OPEN P_RS_LIST	FOR
			SELECT	SUBSTR(W024.BUDAT, 1, 4) || '-' || SUBSTR(W024.BUDAT, 5, 2) || '-' || SUBSTR(W024.BUDAT, 7, 2) AS CHGDAT,
					W024.MATNR_FROM, M001.MATNR_NM AS MATNR_FROM_NM, W024.CHARG AS LOT_NO, W024.IND_BCD, W024.MATNR_TO, M002.MATNR_NM AS MATNR_TO_NM, W024.MENGE AS PRFM_QTY, W024.SDOC_NO, W024.SDOC_SEQNO,
					CASE	WHEN	W024.CNL_YN = 'N'	THEN	'변경완료'	ELSE '변경취소' END AS GBN
			FROM	TB_WRK024 W024 INNER JOIN TB_MAS001 M001
						ON	W024.WERKS_FROM = M001.WERKS
						AND	W024.MATNR_FROM = M001.MATNR
					INNER JOIN	TB_MAS001 M002
						ON	W024.WERKS_TO = M002.WERKS
						AND	W024.MATNR_TO = M002.MATNR
			WHERE	W024.BUDAT BETWEEN P_SDATE AND P_EDATE
			AND		W024.MATNR_FROM LIKE P_MATNR || '%'
			AND		W024.CNL_YN LIKE P_GBN || '%'
			ORDER BY 1, 2, 4, 5;

		P_SUCCESS := 'Y';
	END IF;
END;
