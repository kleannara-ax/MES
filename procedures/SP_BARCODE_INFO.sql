
  CREATE OR REPLACE EDITIONABLE PROCEDURE "KNRAMES"."SP_BARCODE_INFO" SP_BARCODE_INFO
(
	P_IND_BCD	IN VARCHAR2,
	RS_CODE		OUT VARCHAR2,
	RS_MSG		OUT VARCHAR2,
	Lang	 	IN	VARCHAR2,
	CUR_1		OUT SYS_REFCURSOR
)

AS

V_INVCNT	NUMBER(5) := 0;
V_STKKYCNT	NUMBER(5) := 0;
V_RECDICNT	NUMBER(5) := 0;

BEGIN

	SELECT	NVL(COUNT(*), 0) INTO V_INVCNT
	FROM	TB_INV001
	WHERE	IND_BCD = P_IND_BCD;

DBMS_OUTPUT.PUT_LINE('V_INVCNT = ' || TO_CHAR(V_INVCNT));

	SELECT	NVL(COUNT(*), 0) INTO V_STKKYCNT
	FROM	STKKY@KNRAWMSLINK
	WHERE	LOTA14 = P_IND_BCD;

DBMS_OUTPUT.PUT_LINE('V_STKKYCNT = ' || TO_CHAR(V_STKKYCNT));

	SELECT	NVL(COUNT(*), 0) INTO V_RECDICNT
	FROM	RECDI@KNRAWMSLINK
	WHERE	LOTA14 = P_IND_BCD;

DBMS_OUTPUT.PUT_LINE('V_RECDICNT = ' || TO_CHAR(V_RECDICNT));

	IF V_STKKYCNT = 0 AND V_RECDICNT = 0 THEN
                RS_CODE := 'E';
                RS_MSG := '존재하지 않는 바코드 입니다.';
                RETURN;
	END IF;


	IF V_INVCNT <> 0	THEN
		BEGIN
			OPEN CUR_1 FOR
			SELECT	SUBSTR(I001.PRFM_DT, 1, 4) || '-' || SUBSTR(I001.PRFM_DT, 5, 2) || '-' || SUBSTR(I001.PRFM_DT, 7, 2) AS PRFM_DT
					, I001.MACH_CD
					, M012.MACH_NM
					, CMM.CDESC1
					, M001.MATNR
					, M001.MATNR_NM
					, M001.KAN_NO
					, M001.UNIT
					, I001.LOT_NO
					, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BAG', 'EA', 1) || 'x' || FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BOX', 'BAG', 1) AS BASIC_UNIT
					, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'PAL', 'BOX', 1) AS PALLET_UNIT
			--		, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'PAL', 'BOX', 1) AS RCV_QTY
					, NVL(FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BAG', 'BOX', (SELECT QTSIWH FROM STKKY@KNRAWMSLINK WHERE LOTA14 = I001.IND_BCD ORDER BY STOKKY DESC FETCH FIRST 1 ROW ONLY)), 0) AS BAG_QTY
					, (SELECT QTSIWH FROM STKKY@KNRAWMSLINK WHERE LOTA14 = I001.IND_BCD ORDER BY STOKKY DESC FETCH FIRST 1 ROW ONLY) AS STCK_QTY
			FROM	TB_INV001 I001
						FULL OUTER JOIN STKKY@KNRAWMSLINK STKKY
							ON	I001.WERKS = STKKY.LOTA02
							AND I001.IND_BCD = STKKY.LOTA14
						INNER JOIN TB_MAS001 M001
							ON	I001.WERKS = M001.WERKS
							AND I001.MATNR = M001.MATNR
						INNER JOIN TB_MAS012 M012
							ON	I001.MACH_CD = M012.MACH_CD
						INNER JOIN CMCDV CMM
							ON	M001.PART_DIV = CMM.CMCDVL
							AND CMM.CMCDKY = 'PART_DIV'
			WHERE 	I001.IND_BCD = P_IND_BCD;
			EXCEPTION
				WHEN NO_DATA_FOUND	THEN
					OPEN CUR_1 FOR
					SELECT	SUBSTR(I001.PRFM_DT, 1, 4) || '-' || SUBSTR(I001.PRFM_DT, 5, 2) || '-' || SUBSTR(I001.PRFM_DT, 7, 2) AS PRFM_DT
							, I001.MACH_CD
							, M012.MACH_NM
							, CMM.CDESC1
							, M001.MATNR
							, M001.MATNR_NM
							, M001.KAN_NO
							, M001.UNIT
							, I001.LOT_NO
							, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BAG', 'EA', 1) || 'x' || FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BOX', 'BAG', 1) AS BASIC_UNIT
							, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'PAL', 'BOX', 1) AS PALLET_UNIT
					--		, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'PAL', 'BOX', 1) AS RCV_QTY
							, NVL(FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BAG', 'BOX', (SELECT QTYRCV FROM RECDI@KNRAWMSLINK WHERE LOTA14 = I001.IND_BCD ORDER BY RECVKY DESC FETCH FIRST 1 ROW ONLY)), 0) AS BAG_QTY
							, (SELECT QTYRCV FROM RECDI@KNRAWMSLINK WHERE LOTA14 = I001.IND_BCD ORDER BY RECVKY DESC FETCH FIRST 1 ROW ONLY) AS STCK_QTY
					FROM	TB_INV001 I001
								FULL OUTER JOIN RECDI@KNRAWMSLINK RECDI
									ON	I001.WERKS = RECDI.LOTA02
									AND I001.IND_BCD = RECDI.LOTA14
								INNER JOIN TB_MAS001 M001
									ON	I001.WERKS = M001.WERKS
									AND I001.MATNR = M001.MATNR
								INNER JOIN TB_MAS012 M012
									ON	I001.MACH_CD = M012.MACH_CD
								INNER JOIN CMCDV CMM
									ON	M001.PART_DIV = CMM.CMCDVL
									AND CMM.CMCDKY = 'PART_DIV'
					WHERE 	I001.IND_BCD = P_IND_BCD;
		END;
	ELSIF	V_INVCNT = 0 AND V_STKKYCNT <> 0	THEN
		OPEN CUR_1 FOR
		SELECT	SUBSTR(RE.LOTA11, 1, 4) || '-' || SUBSTR(RE.LOTA11, 5, 2) || '-' || SUBSTR(RE.LOTA11, 7, 2) AS PRFM_DT
				, ' ' MACH_CD
				, ' ' MACH_NM
				, CMM.CDESC1
				, M001.MATNR
				, M001.MATNR_NM
				, M001.KAN_NO
				, M001.UNIT
				, RE.LOTA15 AS LOT_NO
				, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BAG', 'EA', 1) || 'x' || FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BOX', 'BAG', 1) AS BASIC_UNIT
				, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'PAL', 'BOX', 1) AS PALLET_UNIT
		--		, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'PAL', 'BOX', 1) AS RCV_QTY
				, NVL(FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BAG', 'BOX', (SELECT QTSIWH FROM STKKY@KNRAWMSLINK WHERE LOTA14 = RE.LOTA14 ORDER BY STOKKY DESC FETCH FIRST 1 ROW ONLY)), 0) AS BAG_QTY
				, (SELECT QTSIWH FROM STKKY@KNRAWMSLINK WHERE LOTA14 = RE.LOTA14 ORDER BY STOKKY DESC FETCH FIRST 1 ROW ONLY) AS STCK_QTY
		FROM	STKKY@KNRAWMSLINK RE
				INNER	JOIN	TB_MAS001	M001
					ON	RE.MEASKY = M001.MATNR
					AND RE.LOTA02 = M001.WERKS
				INNER	JOIN	CMCDV	CMM
					ON	M001.PART_DIV = CMM.CMCDVL
					AND CMM.CMCDKY = 'PART_DIV'
		WHERE 	RE.LOTA14 = P_IND_BCD;
	ELSIF	V_INVCNT = 0 AND V_RECDICNT <> 0 THEN
		OPEN CUR_1 FOR
		SELECT	SUBSTR(RE.LOTA11, 1, 4) || '-' || SUBSTR(RE.LOTA11, 5, 2) || '-' || SUBSTR(RE.LOTA11, 7, 2) AS PRFM_DT
				, ' ' MACH_CD
				, ' ' MACH_NM
				, CMM.CDESC1
				, M001.MATNR
				, M001.MATNR_NM
				, M001.KAN_NO
				, M001.UNIT
				, RE.LOTA15 AS LOT_NO
				, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BAG', 'EA', 1) || 'x' || FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BOX', 'BAG', 1) AS BASIC_UNIT
				, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'PAL', 'BOX', 1) AS PALLET_UNIT
		--		, FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'PAL', 'BOX', 1) AS RCV_QTY
				, NVL(FN_CHG_UNIT(M001.MATNR, M001.WERKS, 'BAG', 'BOX', (SELECT QTYRCV FROM RECDI@KNRAWMSLINK WHERE LOTA14 = RE.LOTA14 ORDER BY RECVKY DESC FETCH FIRST 1 ROW ONLY)), 0) AS BAG_QTY
				, (SELECT QTYRCV FROM RECDI@KNRAWMSLINK WHERE LOTA14 = RE.LOTA14 ORDER BY RECVKY DESC FETCH FIRST 1 ROW ONLY) AS STCK_QTY
		FROM	RECDI@KNRAWMSLINK RE
				INNER	JOIN	TB_MAS001	M001
					ON	RE.SKUKEY = M001.MATNR
					AND RE.LOTA02 = M001.WERKS
				INNER	JOIN	CMCDV	CMM
					ON	M001.PART_DIV = CMM.CMCDVL
					AND CMM.CMCDKY = 'PART_DIV'
		WHERE 	RE.LOTA14 = P_IND_BCD;
	END IF;

	RS_CODE := 'S';
    RS_MSG := '';
END;
