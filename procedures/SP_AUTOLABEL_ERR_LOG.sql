
  CREATE OR REPLACE EDITIONABLE PROCEDURE "KNRAMES"."SP_AUTOLABEL_ERR_LOG" (
    P_MACH_CD   IN VARCHAR2,
    P_IND_BCD   IN VARCHAR2,
    P_ERR_TYPE  IN VARCHAR2,
    P_ERR_MSG   IN VARCHAR2,
    P_RMK       IN VARCHAR2
)
IS
BEGIN
    INSERT INTO TB_AUTOLABEL_ERR_LOG (
        MACH_CD, IND_BCD, ERR_TYPE, ERR_MSG, RMK, REGDATE
    ) VALUES (
        P_MACH_CD, P_IND_BCD, P_ERR_TYPE, P_ERR_MSG, P_RMK, SYSDATE
    );
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'ERROR: ' || SQLERRM);
END;
