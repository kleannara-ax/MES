
  CREATE OR REPLACE EDITIONABLE PROCEDURE "KNRAMES"."SP_DELETE_IFRCV" 
IS
BEGIN
	-- 거래처(공급사)
	DELETE TB_IFR010	WHERE	IF_GET_DATE <= SYSDATE - 2;

	-- 생산오더 BOM
	DELETE TB_IFR014	WHERE	IF_GET_DATE <= SYSDATE - 1;

	-- 생산오더 화장지 초지
	DELETE TB_IFR015	WHERE	IF_GET_DATE <= SYSDATE - 44;

	-- 생산오더 화장지 가공
	DELETE TB_IFR016	WHERE	IF_GET_DATE <= SYSDATE - 44;

	-- 생산오더 패드
	DELETE TB_IFR017	WHERE	IF_GET_DATE <= SYSDATE - 44;

	-- 생산오더 점보롤
	DELETE TB_IFR018	WHERE	IF_GET_DATE <= SYSDATE - 44;

	-- 생산오더 밀롤, 슬리터
	DELETE TB_IFR019	WHERE	IF_GET_DATE <= SYSDATE - 44;

	-- 생산오더 재단
	DELETE TB_IFR020	WHERE	IF_GET_DATE <= SYSDATE - 44;

	-- 생산오더 포장
	DELETE TB_IFR021	WHERE	IF_GET_DATE <= SYSDATE - 44;

	-- 생산오더 예외생산
	DELETE TB_IFR022	WHERE	IF_GET_DATE <= SYSDATE - 44;

	-- TB_ITFMESLOG	MES 인터페이스 전송결과 > 2024/08/01 강지선 추가
	DELETE FROM TB_ITFMESLOG WHERE CDATE < SYSDATE - 44;

	-- TB_ITFRCVWMSLOG	MES WMS 수신이력 > 2024/08/01 강지선 추가
	DELETE FROM TB_ITFRCVWMSLOG WHERE CDATE < SYSDATE - 44;

	-- TB_ITFRUNLOG	인터페이스 처리이력 > 2024/08/01 강지선 추가
	DELETE FROM TB_ITFRUNLOG WHERE UDATE < SYSDATE - 44;

END SP_DELETE_IFRCV;
/
